const LOCALE_EN: u8 = 0;
const LOCALE_FA: u8 = 1;
static LOCALE: AtomicU8 = AtomicU8::new(LOCALE_EN);
static TABLE: Mutex<Option<HashMap<String, String>>> = Mutex::new(None);

const EMBEDDED_EN: &str = include_str!("../../locale/en.json");
const EMBEDDED_FA: &str = include_str!("../../locale/fa.json");

pub(crate) fn is_fa() -> bool {
    LOCALE.load(Ordering::SeqCst) == LOCALE_FA
}

fn exe_dir() -> PathBuf {
    std::env::current_exe()
        .ok()
        .and_then(|p| p.parent().map(|d| d.to_path_buf()))
        .unwrap_or_else(|| PathBuf::from("."))
}

fn parse_map(json: &str) -> HashMap<String, String> {
    let json = json.trim_start_matches('\u{feff}');
    serde_json::from_str(json).unwrap_or_default()
}

fn overlay_file(map: &mut HashMap<String, String>, dir: &std::path::Path, lang: &str) {
    let path = dir.join("locale").join(format!("{lang}.json"));
    if let Ok(s) = std::fs::read_to_string(&path) {
        map.extend(parse_map(&s));
    }
}

fn load_lang(lang: &str) -> HashMap<String, String> {
    let mut map = parse_map(EMBEDDED_EN);
    if lang == "fa" {
        map.extend(parse_map(EMBEDDED_FA));
    }
    if let Ok(cwd) = std::env::current_dir() {
        overlay_file(&mut map, &cwd, lang);
    }
    overlay_file(&mut map, &exe_dir(), lang);
    map
}

pub(crate) fn apply(pref: &str) {
    let system = crate::core::sys::system_ui_language();
    let code = if pref == "system" || pref.is_empty() {
        system.as_str()
    } else {
        pref
    };
    let loc = if code == "fa" { LOCALE_FA } else { LOCALE_EN };
    LOCALE.store(loc, Ordering::SeqCst);
    crate::rtl::set(crate::core::prefs::ui_lang_is_rtl(pref, &system));
    let lang = if loc == LOCALE_FA { "fa" } else { "en" };
    *TABLE.lock().unwrap() = Some(load_lang(lang));
}

fn lookup(key: Key) -> String {
    let id = key.id();
    if let Ok(guard) = TABLE.lock() {
        if let Some(map) = guard.as_ref() {
            if let Some(s) = map.get(id) {
                return s.clone();
            }
        }
    }
    parse_map(EMBEDDED_EN)
        .get(id)
        .cloned()
        .unwrap_or_else(|| id.to_string())
}

pub(crate) fn t(key: Key) -> String {
    crate::text::ui_text(&lookup(key))
}

pub(crate) fn tf(key: Key, args: &[&str]) -> String {
    let mut out = lookup(key);
    for (i, arg) in args.iter().enumerate() {
        let token = format!("{{{i}}}");
        let value = if is_fa() {
            crate::text::fa_digits(arg)
        } else {
            arg.to_string()
        };
        out = out.replace(&token, &value);
    }
    crate::text::ui_text(&out)
}

pub(crate) fn status_label(status: Status) -> String {
    match status {
        Status::Connecting => t(Key::StatusConnecting),
        Status::Downloading => t(Key::StatusDownloading),
        Status::Paused => t(Key::StatusPaused),
        Status::Done => t(Key::StatusComplete),
        Status::Failed => t(Key::StatusFailed),
    }
}

pub(crate) fn row_status_label(status: Status, scheduled: bool, queued: bool) -> String {
    if scheduled && status == Status::Paused {
        t(Key::StatusScheduled)
    } else if queued && status == Status::Paused {
        t(Key::StatusQueued)
    } else {
        match status {
            Status::Connecting => t(Key::StatusConnecting),
            Status::Downloading => t(Key::StatusActive),
            Status::Paused => t(Key::StatusPaused),
            Status::Done => t(Key::StatusCompleted),
            Status::Failed => t(Key::StatusFailed),
        }
    }
}

pub(crate) fn error(msg: &str) -> String {
    if let Some(rest) = msg.strip_prefix("Could not create the temporary folder: ") {
        return tf(Key::ErrorCreateTemp, &[rest]);
    }
    if let Some(rest) = msg.strip_prefix("Could not move temporary files: ") {
        return tf(Key::ErrorMoveTemp, &[rest]);
    }
    if let Some(rest) = msg.strip_prefix("Could not open the startup registry key (error ") {
        let isolated = crate::text::ltr_isolate(rest.trim_end_matches(')'));
        return tf(Key::ErrorAutostartOpen, &[isolated.as_str()]);
    }
    if let Some(rest) = msg.strip_prefix("Could not find the application path: ") {
        return tf(Key::ErrorAutostartPath, &[rest]);
    }
    if let Some(rest) = msg.strip_prefix("Could not update startup settings (error ") {
        let isolated = crate::text::ltr_isolate(rest.trim_end_matches(')'));
        return tf(Key::ErrorAutostartUpdate, &[isolated.as_str()]);
    }
    match msg {
        "Only http(s) URLs" => t(Key::ErrorOnlyHttp),
        "Pause active downloads before changing the temporary folder" => {
            t(Key::ErrorPauseBeforeTemp)
        }
        "Only http(s) addresses are accepted" => t(Key::ErrorOnlyHttpAddr),
        "Download not found" => t(Key::ErrorDownloadNotFound),
        "Pause the download before changing its address" => t(Key::ErrorPauseBeforeUrl),
        "The download is still stopping — try again in a moment" => t(Key::ErrorStillStopping),
        "a part kept failing" => t(Key::ErrorPartFailing),
        "nothing to assemble" => t(Key::ErrorNothingAssemble),
        other => crate::text::ltr_isolate(other),
    }
}

#[cfg(test)]
pub(crate) static TEST_LOCK: std::sync::Mutex<()> = std::sync::Mutex::new(());

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_key_is_in_locale_files() {
        let _lock = super::TEST_LOCK.lock().unwrap();
        apply("en");
        for key in Key::ALL {
            let en = lookup(*key);
            assert!(!en.is_empty(), "{key:?} missing in en");
        }
        apply("fa");
        for key in Key::ALL {
            let fa = lookup(*key);
            assert!(!fa.is_empty(), "{key:?} missing in fa");
        }
        apply("en");
        assert!(!Key::ALL.is_empty());
    }

    #[test]
    fn apply_fa_sets_rtl_and_locale() {
        let _lock = super::TEST_LOCK.lock().unwrap();
        apply("en");
        assert!(!is_fa());
        assert!(!crate::rtl::on());
        apply("fa");
        assert!(is_fa());
        assert!(crate::rtl::on());
        apply("ar");
        assert!(!is_fa());
        assert!(crate::rtl::on());
        apply("en");
        assert!(!crate::rtl::on());
    }

    #[test]
    fn tf_fills_placeholders() {
        let _lock = super::TEST_LOCK.lock().unwrap();
        apply("en");
        assert_eq!(tf(Key::SelectedCount, &["3"]), "3 selected");
        apply("fa");
        assert_eq!(tf(Key::SelectedCount, &["3"]), "۳ مورد انتخاب‌شده");
        apply("en");
    }
}